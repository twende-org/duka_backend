class Command(BaseCommand):
    help = 'Seed MasterProduct rows for the phone & electronics catalog (idempotent).'

    def add_arguments(self, parser):
        parser.add_argument(
            '--apply', action='store_true',
            help='Actually write the rows (default: dry run)',
        )
        parser.add_argument(
            '--niche', default='electronics',
            help='Niche to stamp on every seeded row (default: electronics)',
        )

    def handle(self, *args, **options):
        apply = options['apply']
        niche = options['niche']

        created = skipped = 0
        for brand, name, category_name, requires_imei, warranty, attributes in CATALOG:
            if apply:
                _, was_created = MasterProduct.objects.get_or_create(
                    brand=brand,
                    name=name,
                    defaults={
                        'category_name': category_name,
                        'niche': niche,
                        'requires_imei': requires_imei,
                        'default_warranty': warranty,
                        'attributes': attributes,
                        'is_verified': True,
                        'is_active': True,
                    },
                )
            else:
                was_created = not MasterProduct.objects.filter(brand=brand, name=name).exists()

            if was_created:
                created += 1
                self.stdout.write(
                    f'  + {brand} {name} ({category_name})'
                    f'{" unit-tracked" if requires_imei else ""}'
                )
            else:
                skipped += 1
                self.stdout.write(f'  = {brand} {name} ({category_name}) already present')

        self.stdout.write('')
        header = 'Catalog seeded' if apply else 'Dry run — nothing written (add --apply)'
        self.stdout.write(self.style.WARNING(header))
        self.stdout.write(
            f'{len(CATALOG)} catalog entries: {created} to create, {skipped} already present.'
        )
